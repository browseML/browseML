//! Writes src/glibc_tables.rs: where the C library's `cos` (on np.hanning's arguments) and `pow(2, s/12)` (on the
//! semitone grid) differ from the correctly rounded value, and in which direction (always one ulp). Run on the
//! reference machine (x86-64 glibc, as production and the golden generator):
//!
//!   cargo run --release --bin gen-tables > src/glibc_tables.rs
//!
//! The table is MEASURED DATA about the C library's results, not its code (glibc's sin/cos is LGPL; nothing of it is
//! copied). tests/xmath.rs re-proves the table against the C library over the whole domain on every native run.
#[cfg(all(target_os = "linux", target_env = "gnu", target_arch = "x86_64"))]
fn main() {
    use overlord_dsp::xmath::{cr_cos, cr_exp2, HANN_MAX_M, SEMI_GRID_MAX};
    extern "C" {
        fn cos(x: f64) -> f64;
        fn pow(x: f64, y: f64) -> f64;
    }
    let dir = |g: f64, c: f64| -> Option<u32> {
        if g.to_bits() == c.to_bits() {
            None
        } else if g == c.next_up() {
            Some(1)
        } else if g == c.next_down() {
            Some(0)
        } else {
            panic!("C library differs by more than one ulp: {g:e} vs {c:e}")
        }
    };
    let mut hann = vec![];
    for m in 2..=HANN_MAX_M {
        let d = (m - 1) as f64;
        let mut n = (m as i64 - 1) % 2;
        while n <= m as i64 - 1 {
            let x = std::f64::consts::PI * (n as f64) / d;
            if let Some(b) = dir(unsafe { cos(x) }, cr_cos(x)) {
                hann.push((((m as u32) << 12 | n as u32) << 1) | b);
            }
            n += 2;
        }
    }
    let mut semi = vec![];
    for i in -SEMI_GRID_MAX..=SEMI_GRID_MAX {
        let y = (i as f64 / 1000.0) / 12.0;
        if let Some(b) = dir(unsafe { pow(2.0, y) }, cr_exp2(y)) {
            semi.push(((i as i32) << 1) | b as i32);
        }
    }
    hann.sort_unstable();
    semi.sort_unstable();
    println!("// SPDX-License-Identifier: MIT OR Apache-2.0");
    println!("// GENERATED by `cargo run --release --bin gen-tables` on x86-64 glibc (do not edit). Measured data: where the C");
    println!("// library's result differs by one ulp from the correctly rounded one. Entry = key << 1 | (1 = one ulp up, 0 = down).");
    println!("// HANN: key = M << 12 | n for cos(pi*n/(M-1)), n >= 0 (cos is even), M <= {HANN_MAX_M}: {} entries.", hann.len());
    println!("// SEMI: key = i for 2^((i/1000)/12), |i| <= {SEMI_GRID_MAX}: {} entries.", semi.len());
    print!("pub(crate) static HANN: [u32; {}] = [", hann.len());
    for (k, v) in hann.iter().enumerate() {
        if k % 10 == 0 {
            print!("\n   ");
        }
        print!(" 0x{v:07x},");
    }
    println!("\n];");
    print!("pub(crate) static SEMI: [i32; {}] = [", semi.len());
    for (k, v) in semi.iter().enumerate() {
        if k % 12 == 0 {
            print!("\n   ");
        }
        print!(" {v},");
    }
    println!("\n];");
}

#[cfg(not(all(target_os = "linux", target_env = "gnu", target_arch = "x86_64")))]
fn main() {
    eprintln!("gen-tables measures glibc on x86-64; run it there");
    std::process::exit(2);
}
