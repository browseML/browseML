    '- measured now: tokens read in total not measured, written not measured; my last answer: first token after not measured, reading at not measured, writing at not measured; CPU not measured; memory I hold not measured, still available not measured; GPU busy not measured, my GPU limit not measured, GPU memory I hold not measured; power not measured, energy per token I write not measured';
