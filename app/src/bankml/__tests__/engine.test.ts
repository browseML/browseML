import { describe, expect, it } from 'vitest';
import { parseModel } from '../../core/context';
import { isRepoId, modelFile, slackWindow } from '../engine';

describe('slackWindow (keeps bankML\'s prompt-cache prefix for 4 turns at a time)', () => {
  const turns = (n: number) => Array.from({ length: n }, (_, i) => i);
  it('keeps everything up to 16', () => {
    expect(slackWindow(turns(0))).toEqual([]);
    expect(slackWindow(turns(16))).toEqual(turns(16));
  });
  it('then drops 4 at once, so the first kept exchange changes every 4 turns', () => {
    const starts = [17, 18, 19, 20, 21, 22, 23, 24, 25].map(n => slackWindow(turns(n))[0]);
    expect(starts).toEqual([4, 4, 4, 4, 8, 8, 8, 8, 12]);
    for (const n of [17, 20, 21, 40, 99]) {
      const w = slackWindow(turns(n));
      expect(w.length).toBeGreaterThanOrEqual(13);
      expect(w.length).toBeLessThanOrEqual(16);
      expect(w[w.length - 1]).toBe(n - 1);
    }
  });
});

describe('.model for each engine', () => {
  it('local: the verified, pinned model, readable by the field', () => {
    const m = parseModel(modelFile('local', { local: { name: 'Bonsai-8B', sha256: 'ab'.repeat(32), bankml: '0.3.8' }, provider: 'Qwen/Qwen3-8B' }));
    expect(m).toMatchObject({ model_facet: 'bankml.local', logical_model: 'Bonsai-8B', pinned: true, model_sha256: 'ab'.repeat(32), bankml: '0.3.8' });
  });
  it('local, not verified yet: not pinned', () => {
    expect(parseModel(modelFile('local', { provider: 'x/y' }))).toMatchObject({ logical_model: 'auto', pinned: false });
  });
  it('hf: the provider model, marked not bankML', () => {
    const text = modelFile('hf', { provider: 'Qwen/Qwen3-8B' });
    expect(text).toContain('NOT bankML');
    expect(parseModel(text)).toMatchObject({ model_facet: 'hf.provider', logical_model: 'Qwen/Qwen3-8B', pinned: false });
  });
  it('accepts only owner/name repository ids', () => {
    expect([isRepoId('Qwen/Qwen3-8B'), isRepoId('auto'), isRepoId('a/b/c'), isRepoId('x y/z')]).toEqual([true, false, false, false]);
  });
});

